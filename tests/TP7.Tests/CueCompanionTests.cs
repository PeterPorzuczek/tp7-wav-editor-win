using System.Buffers.Binary;
using System.Text;
using TP7.Audio;
using TP7.Core;
using Xunit;

namespace TP7.Tests;

public sealed class CueCompanionTests : IDisposable
{
    private readonly string root = Path.Combine(Path.GetTempPath(), "TP7.Tests", Guid.NewGuid().ToString("N"));
    public CueCompanionTests() => Directory.CreateDirectory(root);
    public void Dispose() => Directory.Delete(root, true);

    private WaveDocument Source()
    {
        string path = Path.Combine(root, "source.wav");
        File.WriteAllBytes(path, WaveFixture.Fixture(24, 2, false, false, true, 48000));
        return WaveDocument.Load(path);
    }

    // Independent detector for the uncompressed 48 kHz carrier: at sample 10 a zero
    // symbol reaches +18000, while a one symbol crosses zero. Production uses spectral
    // detection after device resampling and ADPCM; the cross-language test covers that path.
    private static byte[] ReadFrame(byte[] wave)
    {
        var chunks = WaveFixture.Inspect(wave);
        Assert.Equal(48000, BinaryPrimitives.ReadInt32LittleEndian(chunks["fmt "].AsSpan(4)));
        byte[] data = chunks["data"];
        Assert.All(data.Take(14400), b => Assert.Equal(0, b));
        Assert.All(data.TakeLast(14400), b => Assert.Equal(0, b));
        int bytes = (data.Length / 2 - 14400) / (120 * 8);
        byte[] frame = new byte[bytes];
        for (int i = 0; i < bytes * 8; i++)
        {
            short sample = BinaryPrimitives.ReadInt16LittleEndian(data.AsSpan((7200 + i * 120 + 10) * 2));
            frame[i / 8] |= (byte)((sample < 9000 ? 1 : 0) << (7 - i % 8));
        }
        Assert.Equal(Convert.FromHexString("5555555555555555D3916BC5A72E84F0"), frame[..16]);
        return frame;
    }

    private static (string Name, int Rate, uint Frames, double Bpm, uint[] Cues) ReadCompanion(string path)
    {
        byte[] frame = ReadFrame(File.ReadAllBytes(path));
        int length = BinaryPrimitives.ReadUInt16LittleEndian(frame.AsSpan(16));
        Assert.Equal(frame.Length, length + 22);
        using var reader = new BinaryReader(new MemoryStream(frame, 18, length));
        Assert.Equal(1, reader.ReadByte());
        Assert.Equal(0, reader.ReadByte());
        int rate = reader.ReadInt32();
        uint frames = reader.ReadUInt32();
        double bpm = reader.ReadDouble();
        int nameLength = reader.ReadUInt16(), count = reader.ReadUInt16();
        Assert.Equal(0, reader.ReadUInt16());
        string name = Encoding.UTF8.GetString(reader.ReadBytes(nameLength));
        uint[] cues = Enumerable.Range(0, count).Select(_ => reader.ReadUInt32()).ToArray();
        return (name, rate, frames, bpm, cues);
    }

    [Fact]
    public void AudioFrameMatchesBrowserGoldenIncludingUtf8FloatTempoEndpointAndCrc()
    {
        var edit = new EditSnapshot(127.12345, [new(4, 192001), new(2, 96001), new(9, 0)], false);
        byte[] wave = CueCarrier.CreateWave("fixture_音.wav", 96000, 192001, edit);
        byte[] frame = ReadFrame(wave);
        // Generated by tp7-midi cue-carrier.js v1, including length and CRC32.
        Assert.Equal(Convert.FromHexString("330001000077010001ee0200000000a0e6c75f400f0003000000666978747572655fe99fb32e776176000000000177010001ee020011f14d12"), frame[16..]);
        string? fixtureDirectory = Environment.GetEnvironmentVariable("TP7_CARRIER_FIXTURE_DIR");
        if (fixtureDirectory != null)
        {
            Directory.CreateDirectory(fixtureDirectory);
            File.WriteAllBytes(Path.Combine(fixtureDirectory, "fixture_音.cue"), wave);
        }
    }

    [Theory]
    [InlineData(false)]
    [InlineData(true)]
    public void PairUsesExportedRateLengthNameTempoAndAllNativeCueOffsets(bool multitrack)
    {
        using var source = Source();
        using var resampled = multitrack ? StemResampler.Prepare(source, 96000) : null;
        IWaveSource document = multitrack ? new MultitrackDocument(96000, [resampled!]) : source;
        var edit = new EditSnapshot(127.12345, [new(90, document.FrameCount), new(7, 24301), new(6, 24301), new(2, 0)], false);
        string destination = Path.Combine(root, "different_音.wav");
        CueCompanionExport.Export(document, destination, edit);
        using var actual = WaveDocument.Load(destination);
        var companion = ReadCompanion(CueCompanionExport.CompanionPath(destination));
        Assert.Equal(Path.GetFileName(destination), companion.Name);
        Assert.Equal(actual.Format.SampleRate, companion.Rate);
        Assert.Equal(actual.FrameCount, companion.Frames);
        Assert.Equal(actual.InitialTempo, companion.Bpm);
        Assert.Equal(actual.InitialCues.Select(c => checked((uint)c.Frame)), companion.Cues);
        if (!multitrack)
        {
            var before = WaveFixture.Inspect(File.ReadAllBytes(source.FilePath));
            var after = WaveFixture.Inspect(File.ReadAllBytes(destination));
            Assert.Equal(before["data"], after["data"]);
            Assert.Equal(before["JUNK"], after["JUNK"]);
        }
        Assert.Empty(Directory.GetFiles(root, ".tp7-*"));
    }

    [Fact]
    public void ReexportClearsOldCompanionAndNativeMarkersTogether()
    {
        using var source = Source();
        string path = Path.Combine(root, "pair.wav");
        CueCompanionExport.Export(source, path, new(120, [new(1, 0)], false));
        CueCompanionExport.Export(source, path, new(0, [], false));
        using var actual = WaveDocument.Load(path);
        Assert.Empty(actual.InitialCues);
        var companion = ReadCompanion(CueCompanionExport.CompanionPath(path));
        Assert.Empty(companion.Cues);
        Assert.Equal(0, companion.Bpm);
        Assert.False(WaveFixture.Inspect(File.ReadAllBytes(path)).ContainsKey("acid"));
    }

    [Theory]
    [InlineData(false)]
    [InlineData(true)]
    public void FailedWaveCommitRestoresPreviousCompanionOrRemovesNewOne(bool existingCue)
    {
        using var source = Source();
        string path = Path.Combine(root, "locked.wav"), companion = CueCompanionExport.CompanionPath(path);
        File.WriteAllBytes(path, [1, 2, 3]);
        if (existingCue)
            File.WriteAllBytes(companion, [4, 5, 6]);
        using (var locked = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.Read))
        {
            Assert.Throws<IOException>(() => CueCompanionExport.Export(source, path, new(120, [new(1, 0)], false)));
        }
        Assert.Equal(new byte[] { 1, 2, 3 }, File.ReadAllBytes(path));
        if (existingCue)
            Assert.Equal(new byte[] { 4, 5, 6 }, File.ReadAllBytes(companion));
        else
            Assert.False(File.Exists(companion));
        Assert.Empty(Directory.GetFiles(root, ".tp7-*"));
    }

    [Fact]
    public void LockedCompanionDoesNotReplaceWave()
    {
        using var source = Source();
        string path = Path.Combine(root, "pair.wav"), companion = CueCompanionExport.CompanionPath(path);
        File.WriteAllBytes(path, [1, 2, 3]);
        File.WriteAllBytes(companion, [4, 5, 6]);
        using (var locked = new FileStream(companion, FileMode.Open, FileAccess.Read, FileShare.Read))
        {
            Assert.Throws<IOException>(() => CueCompanionExport.Export(source, path, new(120, [new(1, 0)], false)));
        }
        Assert.Equal(new byte[] { 1, 2, 3 }, File.ReadAllBytes(path));
        Assert.Equal(new byte[] { 4, 5, 6 }, File.ReadAllBytes(companion));
        Assert.Empty(Directory.GetFiles(root, ".tp7-*"));
    }

    [Fact]
    public void CancellationDuringWritingPreservesBothDestinations()
    {
        using var source = Source();
        string path = Path.Combine(root, "pair.wav"), companion = CueCompanionExport.CompanionPath(path);
        File.WriteAllBytes(path, [1]);
        File.WriteAllBytes(companion, [2]);
        using var cancellation = new CancellationTokenSource();
        Assert.Throws<OperationCanceledException>(() => CueCompanionExport.Export(source, path, new(120, [new(1, 0)], false),
            new CancelProgress(cancellation), cancellation.Token));
        Assert.Equal(new byte[] { 1 }, File.ReadAllBytes(path));
        Assert.Equal(new byte[] { 2 }, File.ReadAllBytes(companion));
        Assert.Empty(Directory.GetFiles(root, ".tp7-*"));
    }

    private sealed class CancelProgress(CancellationTokenSource cancellation) : IProgress<double>
    {
        public void Report(double value) => cancellation.Cancel();
    }

    [Fact]
    public void InvalidOrOversizedCompanionsFailBeforeChangingFilesAndStemsAreProtected()
    {
        using var source = Source();
        byte[] before = File.ReadAllBytes(source.FilePath);
        var project = new MultitrackDocument(48000, [source]);
        Assert.Throws<IOException>(() => CueCompanionExport.Export(project, source.FilePath, new(120, [], false)));
        Assert.Equal(before, File.ReadAllBytes(source.FilePath));
        var tooMany = new EditSnapshot(120, Enumerable.Range(0, 257).Select(i => new CuePoint((uint)i, i)).ToArray(), false);
        Assert.Throws<InvalidDataException>(() => CueCompanionExport.Export(source, source.FilePath, tooMany));
        Assert.Equal(before, File.ReadAllBytes(source.FilePath));
        Assert.Throws<InvalidDataException>(() => CueCarrier.CreateWave("x.wav", 48000, 48000, new(120, [new(1, 48001)], false)));
        Assert.Throws<InvalidDataException>(() => CueCarrier.CreateWave("x.wav", 48000, uint.MaxValue + 1L, new(120, [], false)));
        Assert.Throws<InvalidDataException>(() => CueCarrier.CreateWave("../x.wav", 48000, 48000, new(120, [], false)));
        Assert.False(File.Exists(CueCompanionExport.CompanionPath(source.FilePath)));
        Assert.Empty(Directory.GetFiles(root, ".tp7-*"));
    }
}
